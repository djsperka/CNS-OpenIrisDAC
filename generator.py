class OpenIrisClientGenerator(EyeDataGenerator):
    def __init__(self, state:GlobalState, server_address='localhost', port=9003):
        super().__init__(state)
        self.server_address = server_address
        self.port = port

    def generate(self):
        logger.info(f"Start Open Iris client for server at {self.server_address}:{self.port}")
        with OpenIrisClient(server_address=self.server_address, port=self.port) as client:
            while self.state.is_running:
                data = client.fetch_next_data()
                yield data


class FakeOpenIrisClientGenerator(EyeDataGenerator):
    def __init__(self, state:GlobalState, server_address='localhost', port=9003):
        super().__init__(state)
        self.server_address = server_address
        self.port = port

    def generate(self):
        with OpenIrisClient(self.server_address, self.port) as client:
            x_gain = 5
            y_gain = 5
            x_noise_scale = 2
            y_noise_scale = 2
            while self.state.is_running:
                data = client.fetch_next_data()
                if self.state.calibrating:
                    data.left.pupil = Point(0,0)
                    x = self.state.calibration_fixation_x * x_gain + x_noise_scale * uniform(-1, 1)
                    y = self.state.calibration_fixation_y * y_gain + y_noise_scale * uniform(-1, 1)
                    data.left.cr = Point(x, y)
                    data.left.p4 = Point(5, 5)
                yield data


class FakeEyeDataGenerator(EyeDataGenerator):
    """Standalone generator of simulated left-eye data (no OpenIrisDPI server needed).

    The gaze (in degrees) moves along a Lissajous path at constant speed, or sits on the
    current fixation point while calibrating. Pupil, CR and P4 positions are generated by
    inverting the current CR (left_cal) and DPI (left_dpi) calibrations, so the pipeline's
    outputs recover the simulated gaze. Noise is added separately to the CR and DPI signals.
    """

    # fixed pupil position in camera pixels (inside the calibrator's valid range)
    PUPIL_XY = (360.0, 225.0)

    def __init__(self, state:GlobalState, speed_deg_per_sec:float=2.0, amplitude_deg:float=5.0,
                 freq_ratio:tuple=(3, 2), cr_noise_deg:float=0.05, dpi_noise_deg:float=0.05):
        super().__init__(state)
        self.t = 0
        self.phase = 0.0
        self.speed_deg_per_sec = speed_deg_per_sec
        self.amplitude_deg = amplitude_deg
        self.freq_ratio = freq_ratio
        self.cr_noise_deg = cr_noise_deg
        self.dpi_noise_deg = dpi_noise_deg

    def _lissajous(self, phase):
        a, b = self.freq_ratio
        A = self.amplitude_deg
        return Point(A*math.sin(a*phase + math.pi/2), A*math.sin(b*phase))

    def _advance_phase(self, dt):
        """Advance the Lissajous phase so the gaze moves speed_deg_per_sec*dt degrees along the path."""
        a, b = self.freq_ratio
        dpath = self.amplitude_deg * math.hypot(a*math.cos(a*self.phase + math.pi/2), b*math.cos(b*self.phase))
        self.phase += self.speed_deg_per_sec * dt / max(dpath, 1e-6)

    def _noise(self, scale):
        return Point(scale * uniform(-1, 1), scale * uniform(-1, 1))

    def _makefakedata(self, t):
        """Generate a EyeData struct with pupil, CR and P4 set so that the current calibrations map
        them to the simulated gaze (plus noise).

        Args:
            t (int): frame number to assign to fake data

        Returns:
            EyeData: Enough of the dict to pass to EyesData()
        """

        if self.state.calibrating:
            # eye sits on the fixation point
            gaze = Point(self.state.calibration_fixation_x, self.state.calibration_fixation_y)
        else:
            gaze = self._lissajous(self.phase)

        # degrees -> volts -> raw signals (cr-pupil and cr-p4) via the current calibrations
        vpd = Point(self.state.calibration_vpdx, self.state.calibration_vpdy)
        crsig = self.state.left_cal.inverse((gaze + self._noise(self.cr_noise_deg)) * vpd)
        dpisig = self.state.left_dpi.inverse((gaze + self._noise(self.dpi_noise_deg)) * vpd)
        pupil = Point(*self.PUPIL_XY)
        cr = pupil + crsig
        p4 = cr - dpisig

        fake_data['Left']['FrameNumber'] = t
        fake_data['Left']['Pupil']['Center']['X'] = float(pupil.x)
        fake_data['Left']['Pupil']['Center']['Y'] = float(pupil.y)
        fake_data['Left']['Pupil']['Size']['Width'] = 40.0
        fake_data['Left']['Pupil']['Size']['Height'] = 40.0
        fake_data['Left']['CRs'][0]['X'] = float(cr.x)
        fake_data['Left']['CRs'][0]['Y'] = float(cr.y)
        fake_data['Left']['CRs'][3]['X'] = float(p4.x)
        fake_data['Left']['CRs'][3]['Y'] = float(p4.y)
        return fake_data

    def generate(self):
        dt = 1/self.state.capture_fps
        next_time = time.perf_counter()
        while self.state.is_running:
            # pace frames at the capture rate
            next_time += dt
            time.sleep(max(0, next_time - time.perf_counter()))

            yield EyesData(self._makefakedata(self.t))

            # Lissajous phase is held while calibrating
            if not self.state.calibrating:
                self._advance_phase(dt)
            self.t += 1



class FileEyeDataGenerator(EyeDataGenerator):
    def __init__(self, filename):
        self._filename = filename

    def generate(self):        
        with open(self._filename,'rb') as f:
            while True:
                try:
                    ed = pickle.load(f)
                    yield ed
                except EOFError:
                    break       
